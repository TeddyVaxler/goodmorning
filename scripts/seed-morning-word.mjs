// Writes SQL for Morning Word.
//
//   node scripts/seed-morning-word.mjs allowed > supabase/migrations/<timestamp>_seed_word_allowed.sql
//     Every five-letter word in public/dictionary.txt, as the list of accepted guesses.
//
//   node scripts/seed-morning-word.mjs answers [file] | psql "<connection string>"
//     Deals the words in the answer file (default scripts/morning-word-answers.txt) that haven't
//     been used yet onto the days after the last scheduled one, in an order the database
//     shuffles. The answer file is gitignored and only the database keeps the schedule, so
//     nobody can narrow their guesses down from the repo. To see what's left:
//       select count(*), max(day) from public.word_answers where day >= public.rush_today();
//     The first run starts today (Central time). Run it again before the answers run out.

import fs from 'node:fs';
import path from 'node:path';

const mode = process.argv[2];
const read = (file) => fs.readFileSync(path.join(process.cwd(), file), 'utf-8');
const words = (text) => [...new Set(text.split(/\s+/).map((w) => w.trim().toUpperCase()).filter((w) => /^[A-Z]{5}$/.test(w)))];
const values = (list) => list.map((w) => `('${w}')`).join(',');

if (mode === 'allowed') {
  const all = words(read('public/dictionary.txt')).sort();
  const out = ['-- Generated by scripts/seed-morning-word.mjs allowed. Do not edit by hand.'];
  for (let i = 0; i < all.length; i += 1000) {
    out.push(`insert into public.word_allowed (word) values ${values(all.slice(i, i + 1000))} on conflict do nothing;`);
  }
  process.stdout.write(out.join('\n') + '\n');
} else if (mode === 'answers') {
  const answers = words(read(process.argv[3] ?? 'scripts/morning-word-answers.txt').replace(/^#.*$/gm, ''));
  // Answers are always valid guesses, even if the dictionary lacks one
  process.stdout.write(`begin;
insert into public.word_allowed (word) values ${values(answers)} on conflict do nothing;
with pool (word) as (values ${values(answers)}),
unused as (
  select p.word from pool p
  where not exists (select 1 from public.word_answers a where a.word = p.word)
),
start as (
  select coalesce((select max(a.day) + 1 from public.word_answers a), public.rush_today()) as day
)
insert into public.word_answers (day, word)
select start.day + (row_number() over (order by random()))::integer - 1, unused.word
from unused, start;
select count(*) as scheduled, max(day) as last_day from public.word_answers;
commit;
`);
} else {
  console.error('Usage: node scripts/seed-morning-word.mjs allowed|answers');
  process.exit(1);
}
