// Writes SQL that loads the Sunshine dictionary and pre-generates daily boards.
// Run it again (as a new migration) whenever public/custom-dictionary.json changes or
// the seeded boards are about to run out:
//
//   node scripts/seed-sunshine.mjs 2026-10-25 2027-12-31 > supabase/migrations/<timestamp>_seed_sunshine.sql
//
// Boards that already exist are kept (on conflict do nothing), so a day's board never
// changes after people have played it. Needs Node 23.6+ to import the .ts module.

import fs from 'node:fs';
import path from 'node:path';
import { targetWords, generateBoard, encodeRings } from '../lib/sunshine.ts';

const [from, to] = process.argv.slice(2);
if (!/^\d{4}-\d{2}-\d{2}$/.test(from ?? '') || !/^\d{4}-\d{2}-\d{2}$/.test(to ?? '')) {
  console.error('Usage: node scripts/seed-sunshine.mjs <from YYYY-MM-DD> <to YYYY-MM-DD>');
  process.exit(1);
}

const file = JSON.parse(fs.readFileSync(path.join(process.cwd(), 'public', 'custom-dictionary.json'), 'utf-8'));
const targets = targetWords(file);
const quote = (s) => `'${s.replace(/'/g, "''")}'`;

const out = [];
out.push('-- Generated by scripts/seed-sunshine.mjs. Do not edit by hand.');
out.push('');
out.push('-- Dictionary: replaced wholesale, so removed words stop counting');
out.push('delete from public.sunrise_words;');
for (let i = 0; i < targets.length; i += 500) {
  const chunk = targets.slice(i, i + 500).filter((w) => /^[A-Z]{4,6}$/.test(w));
  if (chunk.length) out.push(`insert into public.sunrise_words (word) values ${chunk.map((w) => `(${quote(w)})`).join(',')} on conflict do nothing;`);
}
out.push('');
out.push(`-- Boards from ${from} to ${to}`);

const rows = [];
for (let d = new Date(`${from}T12:00:00Z`); d <= new Date(`${to}T12:00:00Z`); d.setUTCDate(d.getUTCDate() + 1)) {
  const day = d.toISOString().slice(0, 10);
  const { rings, angles } = generateBoard(day, targets);
  rows.push(`(${quote(day)}, array[${encodeRings(rings).map(quote).join(',')}], array[${angles.join(',')}])`);
}
for (let i = 0; i < rows.length; i += 100) {
  out.push(`insert into public.sunrise_boards (game_date, rings, angles) values\n  ${rows.slice(i, i + 100).join(',\n  ')}\non conflict (game_date) do nothing;`);
}
out.push('');

process.stdout.write(out.join('\n') + '\n');
